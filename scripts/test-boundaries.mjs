import 'dotenv/config';
import assert from 'node:assert/strict';
import { createClient } from '@libsql/client';
import { createHash } from 'node:crypto';
const base = 'http://127.0.0.1:3100';
const db = createClient({ url: process.env.MM_DATABASE_URL || 'file:data/mm-feedback.db' });
const existing = (await db.execute('SELECT * FROM mm_acompanhamentos ORDER BY id LIMIT 1')).rows[0];
const id='demo-same-company-test';
await db.execute({sql:'INSERT OR IGNORE INTO mm_acompanhamentos VALUES (?,?,?,?,?)',args:[id,existing.company,'Segundo acompanhamento de teste','Teste','Em andamento']});
const before=(await db.execute({sql:'SELECT COUNT(*) AS n FROM mm_feedback_respostas r JOIN mm_feedback_links l ON l.id=r.link_id WHERE l.acompanhamento_id=?',args:[existing.id]})).rows[0].n;
const link=await (await fetch(`${base}/api/acompanhamentos/${id}/feedback`,{method:'POST'})).json();
const token=new URL(link.url).searchParams.get('token');
const payload={token,name:'Teste de vínculo por ID',feedbackType:'produtos',productExperience:'Resposta do segundo acompanhamento.',rating:'4'};
assert.equal((await fetch(base+'/api/feedback',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(payload)})).status,200);
const after=(await db.execute({sql:'SELECT COUNT(*) AS n FROM mm_feedback_respostas r JOIN mm_feedback_links l ON l.id=r.link_id WHERE l.acompanhamento_id=?',args:[existing.id]})).rows[0].n;
assert.equal(after,before);
const expired=await (await fetch(`${base}/api/acompanhamentos/${id}/feedback`,{method:'POST'})).json();
const expiredToken=new URL(expired.url).searchParams.get('token');
await db.execute({sql:'UPDATE mm_feedback_links SET expires_at=? WHERE token_hash=?',args:[Date.now()-1000,createHash('sha256').update(expiredToken).digest('hex')]});
assert.equal((await fetch(base+'/api/convite?token='+expiredToken)).status,410);
assert.equal((await fetch(base+'/api/feedback',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({...payload,token:expiredToken})})).status,410);
db.close();
console.log('PASS: acompanhamentos da mesma empresa isolados pelo ID; leitura e envio com token expirado bloqueados.');
